import assert from 'node:assert/strict';
import { preflightRestore } from './backup.mjs';
const bytes = new Uint8Array([1,2,3,4]);
const sha256 = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(n => n.toString(16).padStart(2,'0')).join('');
const track = {id:'source-1', sha256, name:'Test.wav', size:4, type:'audio/wav', variant:'original'};
const fixture = () => ({format:'wood-string-export',version:1,items:[{track:{...track},audio:btoa(String.fromCharCode(...bytes))}],queue:['source-1']});
const original = [{...track,id:'existing-1',cached:true}];
const snapshot = JSON.stringify(original);
const good = await preflightRestore(fixture(),original,10*1048576);
assert.equal(good.prepared.length,1);
const invalidSecond=fixture();invalidSecond.items.push({track:{...track,id:'source-2'},audio:'AAAA'});
await assert.rejects(()=>preflightRestore(invalidSecond,original,10*1048576),/verification/);
assert.equal(JSON.stringify(original),snapshot,'preflight must not mutate existing catalog');
const invalidType=fixture();invalidType.items[0].track.type='text/html';
await assert.rejects(()=>preflightRestore(invalidType,original,10*1048576),/metadata/);
const duplicate=fixture();duplicate.items.push(duplicate.items[0]);
await assert.rejects(()=>preflightRestore(duplicate,original,10*1048576),/metadata/);
const conflict=fixture();
await assert.rejects(()=>preflightRestore(conflict,[{...track,sha256:'0'.repeat(64)}],10*1048576),/conflicts/);
const missing=fixture();missing.queue=['missing'];
await assert.rejects(()=>preflightRestore(missing,original,10*1048576),/missing music/);
await assert.rejects(()=>preflightRestore(fixture(),[{...track,id:'large',sha256:'1'.repeat(64),size:20*1048576,cached:true}],10*1048576),/budget/);
const variants=fixture();variants.items.push({track:{...track,id:'revision-2',variant:'solo'},audio:variants.items[0].audio});
assert.equal((await preflightRestore(variants,[],10*1048576)).prepared.length,2);
console.log('PASS: restore preflight validity, invalid second item, types, duplicate IDs, identity conflicts, queue references, budget, same-byte variants');
